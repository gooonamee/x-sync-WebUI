// Current language - Default to Traditional Chinese 'zh-TW'
let currentLang = localStorage.getItem('x_sync_lang') || 'zh-TW';

function t(key, params = {}) {
  const dict = I18N_LOCALES[currentLang] || I18N_LOCALES['zh-TW'];
  let str = dict[key] || I18N_LOCALES['zh-TW'][key] || key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

function setLanguage(lang) {
  if (!I18N_LOCALES[lang]) lang = 'zh-TW';
  currentLang = lang;
  localStorage.setItem('x_sync_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();

  // Trigger app state re-render
  if (typeof window.onLanguageChanged === 'function') {
    window.onLanguageChanged(lang);
  }
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (val && val.includes('<') && val.includes('>')) { el.innerHTML = val; } else { el.textContent = val; }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.setAttribute('title', t(key));
  });

  // Update language select dropdowns if any
  const langSelects = document.querySelectorAll('.lang-selector-select');
  langSelects.forEach(sel => {
    sel.value = currentLang;
  });
}
